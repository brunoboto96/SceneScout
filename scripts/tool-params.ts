/**
 * The configuration reference's MCP tool parameters table, rendered from the schemas the built
 * server lists. `npm run tool-params` rewrites it; mcp-check holds the guide equal to this output.
 */
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";

export const TOOL_PARAMS_BEGIN = "<!-- tool-params:begin (generated by `npm run tool-params`; do not edit by hand) -->";
export const TOOL_PARAMS_END = "<!-- tool-params:end -->";
/** These two have tables of their own, with each option's default and meaning. */
export const OWN_TABLE_TOOLS: ReadonlySet<string> = new Set(["scout_attach", "scout_login"]);

export interface ListedTool {
  name: string;
  inputSchema: { properties?: Record<string, unknown>; required?: string[] };
}

export function toolParamsMarkdown(tools: readonly ListedTool[]): string {
  const rows = tools
    .filter((t) => !OWN_TABLE_TOOLS.has(t.name))
    .map((t) => {
      const required = new Set(t.inputSchema.required ?? []);
      const params = Object.keys(t.inputSchema.properties ?? {}).map((p) => `\`${p}\` (${required.has(p) ? "required" : "optional"})`);
      return `| \`${t.name}\` | ${params.length > 0 ? params.join(", ") : "none"} |`;
    });
  return [TOOL_PARAMS_BEGIN, "", "| Tool | Parameters |", "|---|---|", ...rows, "", TOOL_PARAMS_END].join("\n");
}

/** The text between the markers, markers included, or undefined when either is missing. */
export function toolParamsSection(reference: string): string | undefined {
  const a = reference.indexOf(TOOL_PARAMS_BEGIN);
  const b = reference.indexOf(TOOL_PARAMS_END);
  return a < 0 || b < a ? undefined : reference.slice(a, b + TOOL_PARAMS_END.length);
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}` && process.argv[2] === "--write-guide") {
  const file = new URL("../docs/guide/Configuration-reference.md", import.meta.url);
  const text = fs.readFileSync(file, "utf8");
  const section = toolParamsSection(text);
  if (section === undefined) throw new Error("Configuration-reference.md has no tool-params markers");
  const client = new Client({ name: "tool-params", version: "0.0.1" });
  await client.connect(new StdioClientTransport({ command: "node", args: [fileURLToPath(new URL("../dist/mcp-server.js", import.meta.url))] }));
  try {
    const { tools } = await client.listTools();
    fs.writeFileSync(
      file,
      text.replace(section, () => toolParamsMarkdown(tools)),
    );
  } finally {
    await client.close();
  }
  console.log("Configuration-reference.md updated");
}
